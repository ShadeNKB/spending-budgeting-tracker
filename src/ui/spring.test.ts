describe('spring: framer-motion parity', () => {
  it.each(GOLDENS)(
    'k $stiffness c $damping, $from to $to at $velocity/s, matches framer every 20 ms',
    (golden) => {
      const s = spring(golden)
      golden.every20ms.forEach((value, i) => {
        expect(s.at(i * 20), `t = ${String(i * 20)} ms`).toBeCloseTo(value, 3)
      })
    },
  )

  it.each(GOLDENS)(
    'k $stiffness c $damping, $from to $to at $velocity/s, rests when framer does',
    (golden) => {
      expect(spring(golden).duration).toBe(golden.restAt)
    },
  )

  it.each(GOLDENS)(
    'k $stiffness c $damping, $from to $to at $velocity/s, moves at framer’s velocity',
    (golden) => {
      const s = spring(golden)
      ;[0, 50, 100, 200].forEach((t, i) => {
        expect(s.velocityAt(t), `t = ${String(t)} ms`).toBeCloseTo(golden.speeds[i] ?? NaN, 2)
      })
    },
  )

  it('starts where it is, at the velocity it was given, and ends exactly on the target', () => {
    const s = spring({ from: -60, to: 0, velocity: 300, stiffness: 420, damping: 40 })
    expect(s.at(0)).toBe(-60)
    expect(s.velocityAt(0)).toBeCloseTo(300, 9)
    expect(s.at(s.duration)).toBe(0)
    expect(s.at(s.duration - 1)).not.toBe(0)
    expect(s.at(10_000)).toBe(0)
  })

  it('takes a mass of 1 by default', () => {
    const a = spring({ from: 0, to: 100, stiffness: 420, damping: 36 })
    const b = spring({ from: 0, to: 100, stiffness: 420, damping: 36, mass: 1 })
    expect(a.at(37)).toBe(b.at(37))
  })
})

describe('springSamples', () => {
  it('samples the spring at a fixed rate until it rests, the last sample exactly the target', () => {
    const options = { from: -60, to: 0, velocity: -200, stiffness: 420, damping: 40 }
    const s = spring(options)
    const { values, step, duration } = springSamples(options, 120)
    expect(step).toBeCloseTo(1000 / 120, 12)
    expect(values[0]).toBe(-60)
    expect(values.at(-1)).toBe(0)
    expect(duration).toBeCloseTo((values.length - 1) * step, 9)
    for (let i = 0; i < values.length - 1; i++) expect(values[i]).toBe(s.at(i * step))
    // The first sample at rest is the last one: the one before it is still moving.
    expect(s.restsAt((values.length - 2) * step)).toBe(false)
    expect(s.restsAt(duration)).toBe(true)
  })

  it('is one sample, and no time, for a spring already at rest', () => {
    expect(springSamples({ from: -96, to: -96, stiffness: 420, damping: 40 }, 120)).toEqual({
      values: [-96],
      step: 1000 / 120,
      duration: 0,
    })
  })
})

describe('springEasing (CSS linear())', () => {
  it('is the spring’s progress at even points of a fixed duration, ending exactly on 1', () => {
    const stops = springEasing({ stiffness: 380, damping: 40 }, 400, 40)
    expect(stops).toHaveLength(41)
    expect(stops[0]).toBe(0)
    expect(stops.at(-1)).toBe(1)
    const s = spring({ from: 0, to: 1000, stiffness: 380, damping: 40 })
    for (let i = 1; i < 40; i++) {
      expect(stops[i], `stop ${String(i)}`).toBeCloseTo(s.at(i * 10) / 1000, 9)
    }
  })

  it('keeps the overshoot of an underdamped spring', () => {
    const stops = springEasing({ stiffness: 420, damping: 32 }, 350, 40)
    expect(Math.max(...stops)).toBeGreaterThan(1.01)
  })

  it('writes the stops as a linear() easing, 4 decimals, no trailing zeros', () => {
    expect(linearEasing([0, 0.123456, 0.5, 1.019999, 1])).toBe('linear(0, 0.1235, 0.5, 1.02, 1)')
    expect(linearEasing([-0.00001, 1])).toBe('linear(0, 1)')
  })
})
